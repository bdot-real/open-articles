"""Scheduling-domain corpus with deliberately varied document lengths.

Length variation is the point. Document norm correlates with length, and that
is what makes the distance-metric invariant bite.
"""
import random

random.seed(19)

TOPICS = [
    ("recurrence expansion", "daylight saving transition wall clock local time gap shift"),
    ("interval semantics", "half open closed overlap conflict abut booking back to back"),
    ("instant storage", "utc offset iana zone identifier naive timestamp presentation"),
    ("month end recurrence", "clamp skip february thirty first day of month rule"),
    ("availability aggregation", "free busy union merge attendees candidate slot search"),
    ("cancellation tombstones", "deleted occurrence series downstream consumer absence"),
    ("timezone database", "tzdata iana update offset recompute cached derived value"),
    ("notification delivery", "reminder sms email push retry backoff dead letter queue"),
    ("calendar sync", "two way delta token incremental full resync conflict resolution"),
    ("resource booking", "room equipment capacity double booking allocation policy"),
]

FILLER = ["onboarding", "expense policy", "release notes", "capacity review",
          "incident postmortem", "vendor evaluation", "support rota", "training"]


def build(n_filler: int = 500):
    docs, did = [], 0
    for title, terms in TOPICS:
        # Three variants per topic at very different lengths. Same subject,
        # wildly different vector norms.
        for mult, tag in ((1, "short"), (6, "medium"), (20, "long")):
            body = (f"{title}. " + f"{terms} " * mult).strip()
            docs.append({"id": f"d{did:04d}", "title": f"{title} ({tag})",
                         "topic": title, "text": body, "kind": "signal",
                         "length": len(body.split())})
            did += 1

    for i in range(n_filler):
        topic = random.choice(FILLER)
        mult = random.choice([1, 4, 15])
        body = (f"{topic} {i}. " +
                f"scheduling appointment availability notes reference " * mult).strip()
        docs.append({"id": f"d{did:04d}", "title": f"{topic} {i}", "topic": topic,
                     "text": body, "kind": "filler", "length": len(body.split())})
        did += 1
    return docs


def build_queries(n_per_topic: int = 12):
    """Enough queries for the curves to be monotonic rather than noise.

    Ten hand-written queries gave 10% granularity and a staleness curve that
    went down, up, then down again, which is the signature of an underpowered
    measurement rather than a finding. These are generated by sampling term
    subsets per topic, so recall is measured over 120 queries instead.
    """
    r = random.Random(31)
    out = []
    for title, terms in TOPICS:
        pool = terms.split()
        for _ in range(n_per_topic):
            k = r.randint(3, min(6, len(pool)))
            out.append((" ".join(r.sample(pool, k)), title))
    return out


QUERIES = [
    ("meeting repeats when clocks change", "recurrence expansion"),
    ("do back to back bookings clash", "interval semantics"),
    ("store utc or local time", "instant storage"),
    ("recurring on the 31st in february", "month end recurrence"),
    ("find a slot everyone is free", "availability aggregation"),
    ("record a removed occurrence", "cancellation tombstones"),
    ("offsets changed after tzdata update", "timezone database"),
    ("reminder retry after failure", "notification delivery"),
    ("incremental delta sync token", "calendar sync"),
    ("room double booked", "resource booking"),
]

if __name__ == "__main__":
    d = build()
    lens = [x["length"] for x in d if x["kind"] == "signal"]
    print(f"{len(d)} docs, {len(QUERIES)} queries")
    print(f"signal doc lengths: min {min(lens)} max {max(lens)} words")
